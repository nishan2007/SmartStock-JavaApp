-- SmartStock store-server sync transport.
--
-- Store servers call this RPC with a server-only Supabase secret key. Registers
-- never receive that key and continue to communicate with the paired store
-- server over the authenticated LAN API.

CREATE TABLE IF NOT EXISTS public.sync_outbox (
    event_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    event_type text NOT NULL,
    location_id integer,
    device_id text,
    user_id integer,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'PENDING',
    attempts integer NOT NULL DEFAULT 0,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
    synced_at timestamptz,
    origin_event_id uuid,
    origin_location_id integer,
    origin_device_id text,
    origin_created_at timestamptz
);

CREATE INDEX IF NOT EXISTS sync_outbox_status_created_idx
    ON public.sync_outbox(status, created_at);

CREATE TABLE IF NOT EXISTS public.sync_applied_events (
    origin_event_id uuid PRIMARY KEY,
    event_type text NOT NULL,
    origin_location_id integer,
    origin_device_id text,
    applied_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
    cloud_reference text
);

ALTER TABLE public.sync_outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sync_applied_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sync_outbox, public.sync_applied_events
    FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.sync_outbox, public.sync_applied_events TO service_role;

ALTER TABLE public.sync_outbox
    ADD COLUMN IF NOT EXISTS cloud_sequence bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE UNIQUE INDEX IF NOT EXISTS sync_outbox_cloud_sequence_key
    ON public.sync_outbox (cloud_sequence);

CREATE INDEX IF NOT EXISTS sync_outbox_cloud_delta_idx
    ON public.sync_outbox (cloud_sequence, location_id);

CREATE SEQUENCE IF NOT EXISTS public.smartstock_store_row_version_seq;

CREATE TABLE IF NOT EXISTS public.smartstock_store_rows (
    location_id integer NOT NULL,
    table_name text NOT NULL,
    row_key jsonb NOT NULL,
    row_data jsonb NOT NULL,
    row_hash text NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    version_sequence bigint NOT NULL
        DEFAULT nextval('public.smartstock_store_row_version_seq'::regclass),
    source_updated_at timestamptz,
    materialized_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
    PRIMARY KEY (location_id, table_name, row_key),
    CHECK (table_name ~ '^[a-z][a-z0-9_]{0,100}$'),
    CHECK (pg_catalog.length(row_hash) BETWEEN 16 AND 128)
);

CREATE UNIQUE INDEX IF NOT EXISTS smartstock_store_rows_version_key
    ON public.smartstock_store_rows(version_sequence);
CREATE INDEX IF NOT EXISTS smartstock_store_rows_location_version_idx
    ON public.smartstock_store_rows(location_id, version_sequence);

CREATE TABLE IF NOT EXISTS public.smartstock_store_mirror_status (
    location_id integer PRIMARY KEY,
    table_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
    active_row_count bigint NOT NULL DEFAULT 0,
    completed_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
    CHECK (pg_catalog.jsonb_typeof(table_counts) = 'object'),
    CHECK (active_row_count >= 0)
);

ALTER TABLE public.smartstock_store_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smartstock_store_mirror_status ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.smartstock_store_rows FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.smartstock_store_mirror_status FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.smartstock_store_row_version_seq
    FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.smartstock_store_rows TO service_role;
GRANT ALL ON TABLE public.smartstock_store_mirror_status TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.smartstock_store_row_version_seq TO service_role;

CREATE OR REPLACE FUNCTION public.smartstock_materialize_store_rows(
    p_location_id integer,
    p_rows jsonb DEFAULT '[]'::jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_row jsonb;
    v_count integer := 0;
BEGIN
    IF p_location_id IS NULL OR p_location_id <= 0 THEN
        RAISE EXCEPTION 'A valid store location is required.';
    END IF;
    IF pg_catalog.jsonb_typeof(COALESCE(p_rows, '[]'::jsonb)) <> 'array' THEN
        RAISE EXCEPTION 'p_rows must be a JSON array.';
    END IF;
    IF pg_catalog.jsonb_array_length(COALESCE(p_rows, '[]'::jsonb)) > 250 THEN
        RAISE EXCEPTION 'A materialization request cannot contain more than 250 rows.';
    END IF;

    FOR v_row IN
        SELECT value FROM pg_catalog.jsonb_array_elements(COALESCE(p_rows, '[]'::jsonb))
    LOOP
        IF COALESCE(v_row->>'table_name', '') !~ '^[a-z][a-z0-9_]{0,100}$'
           OR pg_catalog.jsonb_typeof(v_row->'row_key') <> 'object'
           OR pg_catalog.jsonb_typeof(v_row->'row_data') <> 'object'
           OR pg_catalog.length(COALESCE(v_row->>'row_hash', '')) NOT BETWEEN 16 AND 128 THEN
            RAISE EXCEPTION 'Invalid materialized store row.';
        END IF;
        IF v_row->>'table_name' LIKE 'sync\_%'
           OR v_row->>'table_name' LIKE 'lan\_%'
           OR v_row->>'table_name' IN (
               'security_audit_events', 'local_auth_cache', 'device_credentials'
           ) THEN
            RAISE EXCEPTION 'Table is not allowed in the cloud store mirror.';
        END IF;

        INSERT INTO public.smartstock_store_rows(
            location_id, table_name, row_key, row_data, row_hash, is_deleted,
            source_updated_at
        )
        VALUES (
            p_location_id,
            v_row->>'table_name',
            v_row->'row_key',
            v_row->'row_data',
            v_row->>'row_hash',
            COALESCE((v_row->>'is_deleted')::boolean, false),
            CASE WHEN COALESCE(v_row->>'source_updated_at', '') = ''
                THEN NULL ELSE (v_row->>'source_updated_at')::timestamptz END
        )
        ON CONFLICT (location_id, table_name, row_key) DO UPDATE
        SET row_data = EXCLUDED.row_data,
            row_hash = EXCLUDED.row_hash,
            is_deleted = EXCLUDED.is_deleted,
            source_updated_at = EXCLUDED.source_updated_at,
            version_sequence = nextval('public.smartstock_store_row_version_seq'::regclass),
            materialized_at = pg_catalog.now()
        WHERE public.smartstock_store_rows.row_hash IS DISTINCT FROM EXCLUDED.row_hash
           OR public.smartstock_store_rows.is_deleted IS DISTINCT FROM EXCLUDED.is_deleted;
        v_count := v_count + 1;
    END LOOP;

    RETURN pg_catalog.jsonb_build_object('acknowledged', v_count);
END
$$;

REVOKE ALL ON FUNCTION public.smartstock_materialize_store_rows(integer, jsonb)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.smartstock_materialize_store_rows(integer, jsonb)
    TO service_role;

CREATE OR REPLACE FUNCTION public.smartstock_finalize_store_mirror(
    p_location_id integer,
    p_table_counts jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_entry record;
    v_total bigint := 0;
BEGIN
    IF p_location_id IS NULL OR p_location_id <= 0
       OR pg_catalog.jsonb_typeof(p_table_counts) <> 'object' THEN
        RAISE EXCEPTION 'A valid location and table-count object are required.';
    END IF;
    FOR v_entry IN SELECT key, value FROM pg_catalog.jsonb_each_text(p_table_counts)
    LOOP
        IF v_entry.key !~ '^[a-z][a-z0-9_]{0,100}$'
           OR v_entry.value !~ '^[0-9]+$' THEN
            RAISE EXCEPTION 'Invalid store mirror table count.';
        END IF;
        v_total := v_total + v_entry.value::bigint;
    END LOOP;

    INSERT INTO public.smartstock_store_mirror_status(
        location_id, table_counts, active_row_count, completed_at
    )
    VALUES (p_location_id, p_table_counts, v_total, pg_catalog.now())
    ON CONFLICT(location_id) DO UPDATE
    SET table_counts=EXCLUDED.table_counts,
        active_row_count=EXCLUDED.active_row_count,
        completed_at=EXCLUDED.completed_at
    WHERE public.smartstock_store_mirror_status.table_counts
              IS DISTINCT FROM EXCLUDED.table_counts
       OR public.smartstock_store_mirror_status.active_row_count
              IS DISTINCT FROM EXCLUDED.active_row_count;
    RETURN pg_catalog.jsonb_build_object(
        'completed', true, 'active_row_count', v_total
    );
END
$$;

REVOKE ALL ON FUNCTION public.smartstock_finalize_store_mirror(integer, jsonb)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.smartstock_finalize_store_mirror(integer, jsonb)
    TO service_role;

CREATE OR REPLACE FUNCTION public.smartstock_store_snapshot(
    p_location_id integer,
    p_after_sequence bigint DEFAULT 0,
    p_limit integer DEFAULT 500
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
    WITH page AS (
        SELECT r.table_name, r.row_key, r.row_data, r.row_hash,
               r.is_deleted, r.version_sequence
        FROM public.smartstock_store_rows r
        WHERE r.location_id = p_location_id
          AND r.version_sequence > GREATEST(COALESCE(p_after_sequence, 0::bigint), 0::bigint)
        ORDER BY r.version_sequence
        LIMIT LEAST(GREATEST(COALESCE(p_limit, 500), 1), 1000)
    )
    SELECT pg_catalog.jsonb_build_object(
        'rows', COALESCE(
            pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'table_name', table_name,
                    'row_key', row_key,
                    'row_data', row_data,
                    'row_hash', row_hash,
                    'is_deleted', is_deleted,
                    'sequence', version_sequence
                )
                ORDER BY version_sequence
            ),
            '[]'::jsonb
        ),
        'next_cursor', COALESCE(pg_catalog.max(version_sequence), p_after_sequence, 0)
    )
    FROM page
$$;

REVOKE ALL ON FUNCTION public.smartstock_store_snapshot(integer, bigint, integer)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.smartstock_store_snapshot(integer, bigint, integer)
    TO service_role;

CREATE OR REPLACE FUNCTION public.smartstock_store_snapshot_manifest(p_location_id integer)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
    SELECT pg_catalog.jsonb_build_object(
        'tables', COALESCE(
            pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'name', counts.table_name,
                    'row_count', counts.row_count
                )
                ORDER BY counts.table_name
            ),
            '[]'::jsonb
        )
    )
    FROM (
        SELECT entry.key AS table_name, entry.value::bigint AS row_count
        FROM public.smartstock_store_mirror_status s,
             LATERAL pg_catalog.jsonb_each_text(s.table_counts) entry
        WHERE s.location_id = p_location_id
    ) counts
$$;

REVOKE ALL ON FUNCTION public.smartstock_store_snapshot_manifest(integer)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.smartstock_store_snapshot_manifest(integer)
    TO service_role;

