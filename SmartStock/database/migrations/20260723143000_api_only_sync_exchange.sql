CREATE OR REPLACE FUNCTION public.smartstock_sync_manifest()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
    v_table record;
    v_count bigint;
    v_tables jsonb := '[]'::jsonb;
BEGIN
    FOR v_table IN
        SELECT c.relname AS table_name
        FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relkind IN ('r', 'p')
        ORDER BY c.relname
    LOOP
        EXECUTE pg_catalog.format('SELECT count(*) FROM public.%I', v_table.table_name)
            INTO v_count;
        v_tables := v_tables || pg_catalog.jsonb_build_array(
            pg_catalog.jsonb_build_object(
                'name', v_table.table_name,
                'row_count', v_count,
                'columns', (
                    SELECT COALESCE(
                        pg_catalog.jsonb_agg(a.attname ORDER BY a.attnum),
                        '[]'::jsonb
                    )
                    FROM pg_catalog.pg_attribute a
                    JOIN pg_catalog.pg_class tc ON tc.oid = a.attrelid
                    JOIN pg_catalog.pg_namespace tn ON tn.oid = tc.relnamespace
                    WHERE tn.nspname = 'public'
                      AND tc.relname = v_table.table_name
                      AND a.attnum > 0
                      AND NOT a.attisdropped
                )
            )
        );
    END LOOP;

    RETURN pg_catalog.jsonb_build_object(
        'tables', v_tables,
        'generated_at', pg_catalog.now()
    );
END
$$;

REVOKE ALL ON FUNCTION public.smartstock_sync_manifest()
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.smartstock_sync_manifest()
    TO service_role;

COMMENT ON FUNCTION public.smartstock_sync_manifest()
    IS 'Server-only schema and recovery row-count manifest for SmartStock.';

