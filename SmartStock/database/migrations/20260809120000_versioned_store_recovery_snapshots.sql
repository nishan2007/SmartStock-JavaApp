CREATE OR REPLACE FUNCTION public.smartstock_store_snapshot(
    p_location_id integer,
    p_after_sequence bigint DEFAULT 0,
    p_limit integer DEFAULT 500
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
    WITH current_generation AS (
        SELECT s.current_generation_id
        FROM public.smartstock_store_mirror_status s
        JOIN public.smartstock_store_snapshot_generations g
          ON g.generation_id = s.current_generation_id AND g.status = 'COMPLETE'
        WHERE s.location_id = p_location_id
    ), page AS (
        SELECT r.table_name, r.row_key, r.row_data, r.row_hash,
               r.source_updated_at, r.row_sequence
        FROM public.smartstock_store_snapshot_rows r
        JOIN current_generation g ON g.current_generation_id = r.generation_id
        WHERE r.row_sequence > GREATEST(COALESCE(p_after_sequence, 0::bigint), 0::bigint)
        ORDER BY r.row_sequence
        LIMIT LEAST(GREATEST(COALESCE(p_limit, 500), 1), 1000)
    )
    SELECT pg_catalog.jsonb_build_object(
        'generation_id', (SELECT current_generation_id FROM current_generation),
        'rows', COALESCE(pg_catalog.jsonb_agg(
            pg_catalog.jsonb_build_object(
                'table_name', table_name,
                'row_key', row_key,
                'row_data', row_data,
                'row_hash', row_hash,
                'is_deleted', false,
                'sequence', row_sequence,
                'source_updated_at', source_updated_at
            ) ORDER BY row_sequence
        ), '[]'::jsonb),
        'next_cursor', COALESCE(pg_catalog.max(row_sequence), p_after_sequence, 0)
    )
    FROM page
$$;

