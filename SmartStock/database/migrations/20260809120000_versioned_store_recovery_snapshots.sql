-- Immutable, completed recovery generations for the local-first store mirror.
--
-- smartstock_store_rows remains the current synchronization/read cache. Recovery
-- reads are pinned to a completed generation so an interrupted materialization
-- can never expose a mixture of the previous and next backup.

CREATE TABLE IF NOT EXISTS public.smartstock_store_snapshot_generations (
    generation_id uuid PRIMARY KEY,
    location_id integer NOT NULL,
    status text NOT NULL DEFAULT 'BUILDING'
        CHECK (status IN ('BUILDING', 'COMPLETE')),
    table_counts jsonb NOT NULL DEFAULT '{}'::jsonb
        CHECK (pg_catalog.jsonb_typeof(table_counts) = 'object'),
    active_row_count bigint NOT NULL DEFAULT 0 CHECK (active_row_count >= 0),
    based_on_generation_id uuid
        REFERENCES public.smartstock_store_snapshot_generations(generation_id),
    started_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
    completed_at timestamptz,
    CHECK ((status = 'BUILDING' AND completed_at IS NULL)
        OR (status = 'COMPLETE' AND completed_at IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS smartstock_store_snapshot_one_building_idx
    ON public.smartstock_store_snapshot_generations(location_id)
    WHERE status = 'BUILDING';
CREATE INDEX IF NOT EXISTS smartstock_store_snapshot_completed_idx
    ON public.smartstock_store_snapshot_generations(location_id, completed_at DESC)
    WHERE status = 'COMPLETE';

CREATE TABLE IF NOT EXISTS public.smartstock_store_snapshot_rows (
    generation_id uuid NOT NULL
        REFERENCES public.smartstock_store_snapshot_generations(generation_id)
        ON DELETE CASCADE,
    location_id integer NOT NULL,
    table_name text NOT NULL CHECK (table_name ~ '^[a-z][a-z0-9_]{0,100}$'),
    row_key jsonb NOT NULL,
    row_data jsonb NOT NULL,
    row_hash text NOT NULL CHECK (pg_catalog.length(row_hash) BETWEEN 16 AND 128),
    source_updated_at timestamptz,
    row_sequence bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (generation_id, table_name, row_key)
);

CREATE INDEX IF NOT EXISTS smartstock_store_snapshot_rows_page_idx
    ON public.smartstock_store_snapshot_rows(generation_id, table_name, row_sequence);

ALTER TABLE public.smartstock_store_mirror_status
    ADD COLUMN IF NOT EXISTS current_generation_id uuid
        REFERENCES public.smartstock_store_snapshot_generations(generation_id);

ALTER TABLE public.smartstock_store_snapshot_generations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smartstock_store_snapshot_rows ENABLE ROW LEVEL SECURITY;
